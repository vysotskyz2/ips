from __future__ import annotations

import json
import math
from typing import Any


def make_rect_polygon(
    center_lon: float,
    center_lat: float,
    width_m: float,
    height_m: float,
    angle_deg: float = 0.0,
) -> tuple[str, tuple[float, float, float, float], float]:
    """
    Генерирует реалистичный полигон здания/участка в формате GeoJSON MultiPolygon вокруг центра,
    возвращает (geojson_str, (min_lon, min_lat, max_lon, max_lat), area_sqm).
    """
    lat_rad = math.radians(center_lat)
    m_per_deg_lat = 111_132.0
    m_per_deg_lon = 111_320.0 * math.cos(lat_rad)

    hw = width_m / 2.0
    hh = height_m / 2.0
    corners_m = [(-hw, -hh), (hw, -hh), (hw, hh), (-hw, hh), (-hw, -hh)]

    theta = math.radians(angle_deg)
    cos_t = math.cos(theta)
    sin_t = math.sin(theta)

    ring: list[list[float]] = []
    lons: list[float] = []
    lats: list[float] = []

    for dx_m, dy_m in corners_m:
        rx = dx_m * cos_t - dy_m * sin_t
        ry = dx_m * sin_t + dy_m * cos_t
        lon = round(center_lon + rx / m_per_deg_lon, 6)
        lat = round(center_lat + ry / m_per_deg_lat, 6)
        ring.append([lon, lat])
        lons.append(lon)
        lats.append(lat)

    geojson = json.dumps({"type": "MultiPolygon", "coordinates": [[ring]]}, ensure_ascii=False)
    bbox = (min(lons), min(lats), max(lons), max(lats))
    area_sqm = round(width_m * height_m, 1)
    return geojson, bbox, area_sqm


